// Print 1 to 100

let line = " "
for(let count=1;count<=100;count++) {
    // console.log(count);
    line+=count+" "
}
console.log(line);


// Reverse 100 to 0

let lane = " "
for(let reverse=100;reverse>=0;reverse--) {
   
    lane+=reverse+" "
}
console.log(lane);

// Even number 1 to 100

let number = " "
for(let even=1;even<=100;even++){
    if(even%2===0) {
    
        number+=even+" "
    }
}
console.log(number);

// odd number 1 to 100

let num = " "
for(let odd=1;odd<=100;odd++){
    if(odd%2===1) {
    
        num+=odd+" "
    }
}
console.log(num);


